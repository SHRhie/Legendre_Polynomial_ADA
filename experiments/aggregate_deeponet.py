"""PI-DeepONet re-run aggregation: corrected Table 4 + Fig 6 replacement.

Outputs to <repo>/results/deeponet_rev/:
  runs.csv, table4_replacement.csv   per-arch x model seed statistics
  fig6_replacement.png               rel-L2 vs Re (median over seeds + IQR band)
  report.md
"""
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agg_common import RESULTS, fmt_sci, mean_std
from paths import runs_dir
from plot_style import apply_style, savefig, panel_label, LETTERS
import matplotlib.pyplot as plt

DODIR = runs_dir('deeponet', 'deeponet_rev')
OUT = os.path.join(RESULTS, 'deeponet_rev')
os.makedirs(OUT, exist_ok=True)

WIDTHS = [8, 16, 32, 64]
MODELS = ['VAN', 'LPA_K3_N16']
MODEL_LABELS = {'VAN': 'PI-DeepONet', 'LPA_K3_N16': 'LPA-PI-DeepONet'}
MODEL_COLORS = {'VAN': '#000000', 'LPA_K3_N16': '#d62728'}
VARS = [('l2_u', r'$u$-velocity'), ('l2_v', r'$v$-velocity'), ('l2_p', 'pressure')]
RE_TRAIN = [50, 100, 150]


def load_runs():
    rows = []
    for p in sorted(glob.glob(os.path.join(DODIR, 'run_*.json'))):
        with open(p) as f:
            rows.append(json.load(f))
    return pd.DataFrame(rows)


def load_sweep(nn, key, trial):
    p = os.path.join(DODIR, 're_sweep_3_%d_%s_%d.csv' % (nn, key, trial))
    if not os.path.exists(p):
        return None
    return pd.read_csv(p)


def main():
    apply_style()
    df = load_runs()
    if df.empty:
        print('[deeponet] no runs yet')
        return
    df.to_csv(os.path.join(OUT, 'runs.csv'), index=False)

    vcols = ['l2_u_ref', 'l2_v_ref', 'l2_p_ref',
             'sweep_median_l2_u', 'sweep_median_l2_v', 'sweep_median_l2_p',
             'n_params', 'time_train']
    summ = mean_std(df, ['nn', 'key_id'], vcols).sort_values(['nn', 'key_id'])
    summ.to_csv(os.path.join(OUT, 'table4_replacement.csv'), index=False)

    # Fig 6 replacement: rel-L2 vs Re, median over seeds + IQR band
    widths_here = [w for w in WIDTHS if w in set(df.nn)]
    fig, axes = plt.subplots(len(widths_here), 3,
                             figsize=(11.0, 2.9 * len(widths_here)),
                             sharex=True, squeeze=False)
    fig.subplots_adjust(hspace=0.12, wspace=0.32)
    for i, nn in enumerate(widths_here):
        for j, (var, vlabel) in enumerate(VARS):
            ax = axes[i][j]
            for key in MODELS:
                curves = []
                for trial in range(5):
                    s = load_sweep(nn, key, trial)
                    if s is not None:
                        curves.append(s[var].values)
                if not curves:
                    continue
                A = np.vstack(curves)
                Re = np.arange(1, A.shape[1] + 1)
                med = np.median(A, axis=0)
                q1, q3 = np.percentile(A, [25, 75], axis=0)
                ax.semilogy(Re, med, color=MODEL_COLORS[key], lw=1.3,
                            label=MODEL_LABELS[key] if (i == 0 and j == 0) else None)
                ax.fill_between(Re, q1, q3, color=MODEL_COLORS[key], alpha=0.18, lw=0)
            for rt in RE_TRAIN:
                ax.axvline(rt, color='gray', lw=0.6, ls=':')
            if i == 0:
                ax.set_title(vlabel, fontsize=13)
            if i == len(widths_here) - 1:
                ax.set_xlabel(r'$Re$')
            if j == 0:
                ax.set_ylabel('%d neurons\n' % nn + r'Relative $L_2$')
            panel_label(ax, LETTERS[i * len(VARS) + j], loc='upper left', pad=0.075)
    axes[0][0].legend(fontsize=10, loc='upper right')
    savefig(fig, os.path.join(OUT, 'fig6_replacement.png'))

    # report
    lines = []
    lines.append('# PI-DeepONet re-run (corrected Table 4 / Fig 6)\n')
    lines.append('**Why re-run:** the published Table 4 was generated by a notebook that '
                 'misread acc_hist columns (reported u/v/p were actually L1-pressure, '
                 'L2-u, L2-v), its 3/16 baseline row matches no surviving artifact, values '
                 'were single-run errors at Re=40 only, and the 3/32, 3/64 architectures '
                 'were computed but omitted. See results/manuscript_audit/report.md.\n')
    lines.append('**Protocol:** Variant B, latent 64, head 16, LPA K=3/N_p=16 for all LPA '
                 'rows, Adam 5000 steps @ lr 2e-3, loss = 0.1*PDE + BC, N_int=10000, '
                 'N_B=200, domain [0,1]x[-0.5,1.5], Re_train {50,100,150}, 5 seeds '
                 '(1234+trial), Re sweep 1..199 on a 100x100 grid.\n')
    lines.append('## Corrected Table 4 (rel-L2 at Re=40, mean ± std (median), n=5)\n')
    lines.append('| width | model | u | v | p | sweep median u (Re 1-199) | params |')
    lines.append('|---|---|---|---|---|---|---|')
    for _, r in summ.iterrows():
        lines.append('| %d | %s | %s | %s | %s | %s | %d |' % (
            r['nn'], MODEL_LABELS.get(r['key_id'], r['key_id']),
            fmt_sci(r['l2_u_ref_mean'], r['l2_u_ref_std']),
            fmt_sci(r['l2_v_ref_mean'], r['l2_v_ref_std']),
            fmt_sci(r['l2_p_ref_mean'], r['l2_p_ref_std']),
            fmt_sci(r['sweep_median_l2_u_mean'], r['sweep_median_l2_u_std']),
            r['n_params_mean']))
    lines.append('\n- `fig6_replacement.png` — rel-L2 vs Re (median over 5 seeds, IQR band; '
                 'dotted lines mark training Re).')
    lines.append('- Full sweep aggregates (v, p, means) in `table4_replacement.csv`; '
                 'per-run configs in `runs.csv`.')
    with open(os.path.join(OUT, 'report.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('[deeponet] wrote %s' % OUT)


if __name__ == '__main__':
    main()
